@dataclass
class SyntheticSensorConfig:
    """
    Configuration parameters for synthetic sensor generation.

    Attributes
    ----------
    sampling_rate_hz : float
        Sampling frequency in Hertz (readings per second). Default is 1.0 Hz.
    duration_seconds : float
        Total duration of the generated signal in seconds. Default is 60.0s.
    random_seed : int, optional
        Seed for deterministic random number generation. Default is 42.
    noise_intensity : float
        Scale factor for random Gaussian additive noise. Default is 0.05.
    missing_prob : float
        Probability of random packet dropout / missing reading per sample. Default is 0.05.
    artifact_prob : float
        Probability of transient motion artifacts occurring. Default is 0.05.
    drift_magnitude : float
        Net magnitude of baseline drift over the duration. Default is 5.0 (bpm / % / g).
    scenario : str
        Target scenario identifier. Default is 'NORMAL'.
    start_time : pd.Timestamp, optional
        Initial timestamp for time series. Default is 2026-01-01 00:00:00 UTC.
    baseline_hr : float
        Baseline resting heart rate in bpm. Default is 72.0 bpm.
    baseline_spo2 : float
        Baseline blood oxygen saturation in percent. Default is 98.0%.
    baseline_accel : float
        Baseline stationary acceleration magnitude in g. Default is 1.0 g.
    """
    sampling_rate_hz: float = 1.0
    duration_seconds: float = 60.0
    random_seed: Optional[int] = 42
    noise_intensity: float = 0.05
    missing_prob: float = 0.05
    artifact_prob: float = 0.05
    drift_magnitude: float = 5.0
    scenario: str = SCENARIO_NORMAL
    start_time: Optional[pd.Timestamp] = None
    baseline_hr: float = 72.0
    baseline_spo2: float = 98.0
    baseline_accel: float = 1.0

    def __post_init__(self) -> None:
        if self.sampling_rate_hz <= 0:
            raise ValueError(f"sampling_rate_hz must be positive, got {self.sampling_rate_hz}")
        if self.duration_seconds <= 0:
            raise ValueError(f"duration_seconds must be positive, got {self.duration_seconds}")
        if self.start_time is None:
            self.start_time = pd.Timestamp("2026-01-01 00:00:00", tz="UTC")


class SyntheticSensorGenerator:
    """
    Deterministic synthetic wearable sensor stream generator.

    Simulates physiological test streams for photoplethysmography (Heart Rate, SpO2)
    and tri-axial / magnitude inertial measurement units (Accelerometer).
    """

    def __init__(self, config: Optional[SyntheticSensorConfig] = None) -> None:
        """Initialize generator with configuration."""
        self.config = config or SyntheticSensorConfig()

    def _get_rng(self, offset: int = 0) -> np.random.RandomState:
        """Obtain deterministic RandomState instance."""
        if self.config.random_seed is not None:
            seed = (self.config.random_seed + offset) % (2**31 - 1)
            return np.random.RandomState(seed)
        return np.random.RandomState()

    def _generate_time_grid(self) -> Tuple[np.ndarray, pd.DatetimeIndex]:
        """Generate relative time array in seconds and uniform timestamp index."""
        dt = 1.0 / self.config.sampling_rate_hz
        n_points = int(round(self.config.duration_seconds * self.config.sampling_rate_hz))
        t = np.arange(n_points) * dt
        start = self.config.start_time or pd.Timestamp("2026-01-01 00:00:00", tz="UTC")
        timestamps = pd.date_range(start=start, periods=n_points, freq=pd.to_timedelta(dt, unit="s"))
        return t, timestamps

    def generate_heart_rate(
        self,
        scenario: Optional[str] = None,
        config_override: Optional[SyntheticSensorConfig] = None,
    ) -> pd.DataFrame:
        """
        Generate synthetic Heart Rate (bpm) signal.

        Parameters
        ----------
        scenario : str, optional
            Scenario override. If None, uses config.scenario.
        config_override : SyntheticSensorConfig, optional
            Custom config override.

        Returns
        -------
        pd.DataFrame
            Tidy DataFrame conforming to output schema.
        """
        cfg = config_override or self.config
        scen = scenario or cfg.scenario
        t, timestamps = self._generate_time_grid()
        n = len(t)
        rng = self._get_rng(offset=101)

        # Baseline physiological signal: sinus oscillation ~0.25 Hz + low freq vasomotor ~0.1 Hz
        base_signal = (
            cfg.baseline_hr
            + 2.0 * np.sin(2 * np.pi * 0.25 * t)
            + 1.0 * np.sin(2 * np.pi * 0.10 * t)
            + rng.normal(0, 0.5 * (1.0 + cfg.noise_intensity), size=n)
        )

        signal_values = np.copy(base_signal)
        statuses = [STATUS_VALID] * n

        if scen == SCENARIO_NORMAL:
            pass  # Nominal baseline

        elif scen == SCENARIO_MOTION_ARTIFACT:
            # Inject transient erratic motion artifacts (high spikes & jitter)
            n_artifacts = max(1, int(n * cfg.artifact_prob))
            artifact_indices = rng.choice(n, size=n_artifacts, replace=False)
            for idx in artifact_indices:
                window_len = rng.randint(2, max(4, int(5 * cfg.sampling_rate_hz)))
                end_idx = min(n, idx + window_len)
                # Spurious spike / jitter (+30 to +60 bpm artifact)
                spike = rng.uniform(30.0, 60.0)
                signal_values[idx:end_idx] += spike + rng.normal(0, 5.0, size=end_idx - idx)
                for k in range(idx, end_idx):
                    statuses[k] = STATUS_ARTIFACT

        elif scen == SCENARIO_NOISE:
            # Elevated sensor noise
            noise_scale = 5.0 * cfg.noise_intensity
            signal_values += rng.normal(0, noise_scale, size=n)

        elif scen == SCENARIO_MISSING_DATA:
            # Intermittent missing readings / packet dropouts
            mask = rng.rand(n) < cfg.missing_prob
            signal_values[mask] = np.nan
            for k in np.where(mask)[0]:
                statuses[k] = STATUS_MISSING

        elif scen == SCENARIO_SENSOR_DISCONNECT:
            # Continuous disconnection window (e.g. 35% to 65% of stream duration)
            start_disc = int(n * 0.35)
            end_disc = int(n * 0.65)
            signal_values[start_disc:end_disc] = np.nan
            for k in range(start_disc, end_disc):
                statuses[k] = STATUS_DISCONNECTED

        elif scen == SCENARIO_SIGNAL_DRIFT:
            # Gradual upward or downward drift over time
            drift_curve = np.linspace(0, cfg.drift_magnitude, n)
            signal_values += drift_curve
            for k in range(n):
                if statuses[k] == STATUS_VALID:
                    statuses[k] = STATUS_DRIFT

        df = pd.DataFrame({
            "timestamp": timestamps,
            "sensor_type": SENSOR_HEART_RATE,
            "signal_value": signal_values,
            "scenario": scen,
            "signal_status": statuses,
            "is_synthetic": True,
        })
        return df

    def generate_spo2(
        self,
        scenario: Optional[str] = None,
        config_override: Optional[SyntheticSensorConfig] = None,
    ) -> pd.DataFrame:
        """
        Generate synthetic SpO2 (%) signal.

        Parameters
        ----------
        scenario : str, optional
            Scenario override. If None, uses config.scenario.
        config_override : SyntheticSensorConfig, optional
            Custom config override.

        Returns
        -------
        pd.DataFrame
            Tidy DataFrame conforming to output schema.
        """
        cfg = config_override or self.config
        scen = scenario or cfg.scenario
        t, timestamps = self._generate_time_grid()
        n = len(t)
        rng = self._get_rng(offset=202)

        # Baseline oxygen saturation: ~98% with subtle respiration modulation
        base_signal = (
            cfg.baseline_spo2
            + 0.3 * np.sin(2 * np.pi * 0.05 * t)
            + rng.normal(0, 0.15 * (1.0 + cfg.noise_intensity), size=n)
        )
        base_signal = np.clip(base_signal, 70.0, 100.0)

        signal_values = np.copy(base_signal)
        statuses = [STATUS_VALID] * n

        if scen == SCENARIO_NORMAL:
            pass

        elif scen == SCENARIO_MOTION_ARTIFACT:
            # Optical pulse oximetry motion artifact: spurious transient desaturation drops
            n_artifacts = max(1, int(n * cfg.artifact_prob))
            artifact_indices = rng.choice(n, size=n_artifacts, replace=False)
            for idx in artifact_indices:
                window_len = rng.randint(2, max(4, int(4 * cfg.sampling_rate_hz)))
                end_idx = min(n, idx + window_len)
                drop = rng.uniform(8.0, 15.0)
                signal_values[idx:end_idx] -= drop
                signal_values[idx:end_idx] = np.clip(signal_values[idx:end_idx], 70.0, 100.0)
                for k in range(idx, end_idx):
                    statuses[k] = STATUS_ARTIFACT

        elif scen == SCENARIO_NOISE:
            noise_scale = 1.5 * cfg.noise_intensity
            signal_values += rng.normal(0, noise_scale, size=n)
            signal_values = np.clip(signal_values, 70.0, 100.0)

        elif scen == SCENARIO_MISSING_DATA:
            mask = rng.rand(n) < cfg.missing_prob
            signal_values[mask] = np.nan
            for k in np.where(mask)[0]:
                statuses[k] = STATUS_MISSING

        elif scen == SCENARIO_SENSOR_DISCONNECT:
            start_disc = int(n * 0.35)
            end_disc = int(n * 0.65)
            signal_values[start_disc:end_disc] = np.nan
            for k in range(start_disc, end_disc):
                statuses[k] = STATUS_DISCONNECTED

        elif scen == SCENARIO_SIGNAL_DRIFT:
            # Downward baseline desaturation drift
            drift_curve = np.linspace(0, -cfg.drift_magnitude, n)
            signal_values += drift_curve
            signal_values = np.clip(signal_values, 70.0, 100.0)
            for k in range(n):
                if statuses[k] == STATUS_VALID:
                    statuses[k] = STATUS_DRIFT

        df = pd.DataFrame({
            "timestamp": timestamps,
            "sensor_type": SENSOR_SPO2,
            "signal_value": signal_values,
            "scenario": scen,
            "signal_status": statuses,
            "is_synthetic": True,
        })
        return df

    def generate_accelerometer(
        self,
        scenario: Optional[str] = None,
        config_override: Optional[SyntheticSensorConfig] = None,
        movement_mode: str = "stationary",
    ) -> pd.DataFrame:
        """
        Generate synthetic Accelerometer magnitude (g) signal.

        Parameters
        ----------
        scenario : str, optional
            Scenario override. If None, uses config.scenario.
        config_override : SyntheticSensorConfig, optional
            Custom config override.
        movement_mode : str, default='stationary'
            Activity profile: 'stationary' (~1.0g), 'walking' (~1.5 Hz oscillation),
            or 'high_motion' (erratic high-g activity).

        Returns
        -------
        pd.DataFrame
            Tidy DataFrame conforming to output schema.
        """
        cfg = config_override or self.config
        scen = scenario or cfg.scenario
        t, timestamps = self._generate_time_grid()
        n = len(t)
        rng = self._get_rng(offset=303)

        if movement_mode == "walking":
            base_accel = cfg.baseline_accel + 0.4 * np.abs(np.sin(2 * np.pi * 1.5 * t))
        elif movement_mode == "high_motion":
            base_accel = cfg.baseline_accel + 1.2 * np.abs(np.sin(2 * np.pi * 3.0 * t))
        else:
            base_accel = np.full(n, cfg.baseline_accel)

        base_accel += rng.normal(0, 0.02 * (1.0 + cfg.noise_intensity), size=n)
        signal_values = np.copy(base_accel)
        statuses = [STATUS_VALID] * n

        if scen == SCENARIO_NORMAL:
            pass

        elif scen == SCENARIO_MOTION_ARTIFACT:
            # Sudden high-g jolts / movement spikes
            n_artifacts = max(1, int(n * cfg.artifact_prob))
            artifact_indices = rng.choice(n, size=n_artifacts, replace=False)
            for idx in artifact_indices:
                window_len = rng.randint(1, max(3, int(2 * cfg.sampling_rate_hz)))
                end_idx = min(n, idx + window_len)
                jolt = rng.uniform(2.5, 5.0)
                signal_values[idx:end_idx] += jolt
                for k in range(idx, end_idx):
                    statuses[k] = STATUS_ARTIFACT

        elif scen == SCENARIO_NOISE:
            noise_scale = 0.3 * cfg.noise_intensity
            signal_values += rng.normal(0, noise_scale, size=n)

        elif scen == SCENARIO_MISSING_DATA:
            mask = rng.rand(n) < cfg.missing_prob
            signal_values[mask] = np.nan
            for k in np.where(mask)[0]:
                statuses[k] = STATUS_MISSING

        elif scen == SCENARIO_SENSOR_DISCONNECT:
            start_disc = int(n * 0.35)
            end_disc = int(n * 0.65)
            signal_values[start_disc:end_disc] = np.nan
            for k in range(start_disc, end_disc):
                statuses[k] = STATUS_DISCONNECTED

        elif scen == SCENARIO_SIGNAL_DRIFT:
            drift_curve = np.linspace(0, 0.3 * cfg.drift_magnitude, n)
            signal_values += drift_curve
            for k in range(n):
                if statuses[k] == STATUS_VALID:
                    statuses[k] = STATUS_DRIFT

        df = pd.DataFrame({
            "timestamp": timestamps,
            "sensor_type": SENSOR_ACCELEROMETER,
            "signal_value": signal_values,
            "scenario": scen,
            "signal_status": statuses,
            "is_synthetic": True,
        })
        return df

    def generate_scenario(
        self,
        scenario: str,
        sensors: Optional[Sequence[str]] = None,
    ) -> pd.DataFrame:
        """
        Generate multi-sensor dataset for a specified benchmark scenario.

        Parameters
        ----------
        scenario : str
            Scenario name from ALL_SCENARIOS.
        sensors : Sequence[str], optional
            Sensors to include. Defaults to all 3 sensors (heart_rate, spo2, accelerometer).

        Returns
        -------
        pd.DataFrame
            Concatenated tidy DataFrame containing all requested sensor streams.
        """
        if scenario not in ALL_SCENARIOS:
            raise ValueError(f"Unknown scenario '{scenario}'. Available: {ALL_SCENARIOS}")

        selected_sensors = list(sensors or ALL_SENSOR_TYPES)
        dfs: List[pd.DataFrame] = []

        for st in selected_sensors:
            if st == SENSOR_HEART_RATE:
                dfs.append(self.generate_heart_rate(scenario=scenario))
            elif st == SENSOR_SPO2:
                dfs.append(self.generate_spo2(scenario=scenario))
            elif st == SENSOR_ACCELEROMETER:
                dfs.append(self.generate_accelerometer(scenario=scenario))
            else:
                raise ValueError(f"Unknown sensor type '{st}'. Available: {ALL_SENSOR_TYPES}")

        combined = pd.concat(dfs, ignore_index=True)
        # Sort chronologically by timestamp and sensor type
        combined = combined.sort_values(["timestamp", "sensor_type"]).reset_index(drop=True)
        return combined

    def generate_normal_scenario(self) -> pd.DataFrame:
        """Generate nominal baseline multi-sensor scenario."""
        return self.generate_scenario(SCENARIO_NORMAL)

    def generate_motion_artifact_scenario(self) -> pd.DataFrame:
        """Generate motion artifact multi-sensor scenario."""
        return self.generate_scenario(SCENARIO_MOTION_ARTIFACT)

    def generate_noise_scenario(self) -> pd.DataFrame:
        """Generate high noise multi-sensor scenario."""
        return self.generate_scenario(SCENARIO_NOISE)

    def generate_missing_data_scenario(self) -> pd.DataFrame:
        """Generate intermittent missing data / packet dropout scenario."""
        return self.generate_scenario(SCENARIO_MISSING_DATA)

    def generate_sensor_disconnect_scenario(self) -> pd.DataFrame:
        """Generate sensor disconnection fault scenario."""
        return self.generate_scenario(SCENARIO_SENSOR_DISCONNECT)

    def generate_signal_drift_scenario(self) -> pd.DataFrame:
        """Generate gradual baseline drift scenario."""
        return self.generate_scenario(SCENARIO_SIGNAL_DRIFT)


