"""
WEDJAT-X Synthetic Wearable Sensor Data Generator
NASA Space Apps Challenge - Astronaut Health Monitoring Prototype

This module provides a deterministic, highly configurable synthetic wearable sensor
data generator to test WEDJAT-X sensor streaming and real-time intelligence algorithms.

IMPORTANT SCIENTIFIC & ETHICAL NOTICE:
--------------------------------------
All signals generated by this module are STRICTLY SYNTHETIC software test patterns.
They DO NOT represent real NASA astronaut biometric telemetry and MUST NEVER be merged
with NASA OSD-575 laboratory biomarker records or represented as clinical observations.
Every record is explicitly tagged with `is_synthetic = True`.
"""

