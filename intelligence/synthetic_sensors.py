def save_synthetic_dataset(
    df: pd.DataFrame,
    filename: str,
    output_dir: Optional[Union[str, Path]] = None,
) -> Path:
    """
    Save synthetic dataset DataFrame to CSV in target directory.

    Parameters
    ----------
    df : pd.DataFrame
        Synthetic sensor stream.
    filename : str
        Output file name (e.g. 'normal_scenario.csv').
    output_dir : str or Path, optional
        Destination directory. Defaults to 'synthetic_data/'.

    Returns
    -------
    Path
        Path to saved CSV.
    """
    out_dir = Path(output_dir or "synthetic_data")
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / filename
    df.to_csv(out_path, index=False)
    logger.info("Saved synthetic dataset to: %s", out_path)
    return out_path


def generate_all_benchmark_scenarios(
    output_dir: Optional[Union[str, Path]] = None,
    duration_seconds: float = 60.0,
    sampling_rate_hz: float = 1.0,
    random_seed: Optional[int] = 42,
) -> Dict[str, Path]:
    """
    Generate and persist reproducible benchmark datasets for all 6 scenarios.

    Parameters
    ----------
    output_dir : str or Path, optional
        Destination directory. Defaults to 'synthetic_data/'.
    duration_seconds : float, default=60.0
        Duration in seconds.
    sampling_rate_hz : float, default=1.0
        Sampling frequency in Hz.
    random_seed : int, default=42
        Deterministic random seed.

    Returns
    -------
    dict of str -> Path
        Dictionary mapping scenario names to generated CSV file paths.
    """
    out_dir = Path(output_dir or "synthetic_data")
    out_dir.mkdir(parents=True, exist_ok=True)

    results: Dict[str, Path] = {}

    scenarios_map = {
        SCENARIO_NORMAL: generate_normal_scenario,
        SCENARIO_MOTION_ARTIFACT: generate_motion_artifact_scenario,
        SCENARIO_NOISE: generate_noise_scenario,
        SCENARIO_MISSING_DATA: generate_missing_data_scenario,
        SCENARIO_SENSOR_DISCONNECT: generate_sensor_disconnect_scenario,
        SCENARIO_SIGNAL_DRIFT: generate_signal_drift_scenario,
    }

    for scen_name, func in scenarios_map.items():
        fname = f"{scen_name.lower()}_scenario.csv"
        df = func(
            sampling_rate_hz=sampling_rate_hz,
            duration_seconds=duration_seconds,
            random_seed=random_seed,
        )
        saved_path = save_synthetic_dataset(df, filename=fname, output_dir=out_dir)
        results[scen_name] = saved_path

    return results
